// Authentication middleware

const BearerHeaders = Schema.Struct({ authorization: Schema.optionalKey(Schema.String) });

export interface InstancePrincipalShape {
  readonly user: InstanceUser;
  readonly sessionId: string;
}

export class InstancePrincipal extends Context.Service<InstancePrincipal, InstancePrincipalShape>()(
  "@t3tools/contracts/instance/InstancePrincipal",
) {}

/** Any signed-in, enabled user. */
export class InstanceUserAuth extends HttpApiMiddleware.Service<
  InstanceUserAuth,
  { provides: InstancePrincipal }
>()("InstanceUserAuth", {
  error: [InstanceUnauthorizedError, InstanceInternalError],
}) {}

/** A signed-in admin. */
export class InstanceAdminAuth extends HttpApiMiddleware.Service<
  InstanceAdminAuth,
  { provides: InstancePrincipal }
>()("InstanceAdminAuth", {
  error: [InstanceUnauthorizedError, InstanceForbiddenError, InstanceInternalError],
}) {}

export class InstanceWorkspacePrincipal extends Context.Service<
  InstanceWorkspacePrincipal,
  { readonly userId: InstanceUserId }
>()("@t3tools/contracts/instance/InstanceWorkspacePrincipal") {}

/** The calling workspace, proven by `Authorization: Bearer <userId>:<workspace secret>`. */
export class InstanceWorkspaceAuth extends HttpApiMiddleware.Service<
  InstanceWorkspaceAuth,
  { provides: InstanceWorkspacePrincipal }
>()("InstanceWorkspaceAuth", {
  error: [InstanceUnauthorizedError, InstanceInternalError],
}) {}

const p = (path: string) => `${INSTANCE_API_PREFIX}${path}` as const;

const CommonErrors = [InstanceBadRequestError, InstanceInternalError] as const;
const TargetErrors = [...CommonErrors, InstanceNotFoundError, InstanceConflictError] as const;

class InstancePublicApi extends HttpApiGroup.make("public")
  .add(
    HttpApiEndpoint.get("descriptor", p("/descriptor"), {
      success: InstanceDescriptor,
      error: CommonErrors,
    }),
  )
  .add(
    HttpApiEndpoint.post("login", p("/auth/login"), {
      payload: InstanceLoginRequest,
      success: InstanceLoginResult,
      error: [...CommonErrors, InstanceUnauthorizedError, InstanceRateLimitedError],
    }),
  ) {}

class InstanceAccountApi extends HttpApiGroup.make("account")
  .add(
    HttpApiEndpoint.get("me", p("/auth/me"), {
      headers: BearerHeaders,
      success: InstanceMe,
      error: CommonErrors,
    }),
  )
  .add(
    HttpApiEndpoint.post("logout", p("/auth/logout"), {
      headers: BearerHeaders,
      success: InstanceOk,
      error: CommonErrors,
    }),
  )
  .add(
    HttpApiEndpoint.post("changePassword", p("/auth/password"), {
      headers: BearerHeaders,
      payload: InstanceChangePasswordRequest,
      success: InstanceUser,
      error: [...CommonErrors, InstanceRateLimitedError],
    }),
  )
  .add(
    HttpApiEndpoint.get("sessions", p("/auth/sessions"), {
      headers: BearerHeaders,
      success: InstanceSessionList,
      error: CommonErrors,
    }),
  )
  .add(
    HttpApiEndpoint.post("revokeSession", p("/auth/sessions/:sessionId/revoke"), {
      headers: BearerHeaders,
      params: InstanceSessionParams,
      success: InstanceOk,
      error: TargetErrors,
    }),
  )
  .add(
    HttpApiEndpoint.get("workspace", p("/workspace"), {
      headers: BearerHeaders,
      success: InstanceWorkspace,
      error: TargetErrors,
    }),
  )
  .add(
    HttpApiEndpoint.post("workspaceToken", p("/workspace/token"), {
      headers: BearerHeaders,
      success: InstanceWorkspaceTokenResult,
      error: [...TargetErrors, InstanceForbiddenError],
    }),
  )
  .add(
    HttpApiEndpoint.post("restartWorkspace", p("/workspace/restart"), {
      headers: BearerHeaders,
      success: InstanceWorkspace,
      error: TargetErrors,
    }),
  )
  .middleware(InstanceUserAuth) {}

class InstanceAdminApi extends HttpApiGroup.make("admin")
  .add(
    HttpApiEndpoint.get("overview", p("/admin/overview"), {
      headers: BearerHeaders,
      success: InstanceOverview,
      error: CommonErrors,
    }),
  )
  .add(
    HttpApiEndpoint.get("listUsers", p("/admin/users"), {
      headers: BearerHeaders,
      success: InstanceUserList,
      error: CommonErrors,
    }),
  )
  .add(
    HttpApiEndpoint.post("createUser", p("/admin/users"), {
      headers: BearerHeaders,
      payload: InstanceCreateUserRequest,
      success: InstanceCreateUserResult,
      error: TargetErrors,
    }),
  )
  .add(
    HttpApiEndpoint.get("getUser", p("/admin/users/:userId"), {
      headers: BearerHeaders,
      params: InstanceUserParams,
      success: InstanceUserWithWorkspace,
      error: TargetErrors,
    }),
  )
  .add(
    HttpApiEndpoint.post("updateUser", p("/admin/users/:userId"), {
      headers: BearerHeaders,
      params: InstanceUserParams,
      payload: InstanceUpdateUserRequest,
      success: InstanceUserWithWorkspace,
      error: TargetErrors,
    }),
  )
  .add(
    HttpApiEndpoint.post("resetPassword", p("/admin/users/:userId/reset-password"), {
      headers: BearerHeaders,
      params: InstanceUserParams,
      success: InstanceResetPasswordResult,
      error: TargetErrors,
    }),
  )
  .add(
    HttpApiEndpoint.post("deleteUser", p("/admin/users/:userId/delete"), {
      headers: BearerHeaders,
      params: InstanceUserParams,
      payload: InstanceDeleteUserRequest,
      success: InstanceOk,
      error: TargetErrors,
    }),
  )
  .add(
    HttpApiEndpoint.get("userSessions", p("/admin/users/:userId/sessions"), {
      headers: BearerHeaders,
      params: InstanceUserParams,
      success: InstanceSessionList,
      error: TargetErrors,
    }),
  )
  .add(
    HttpApiEndpoint.post(
      "revokeUserSession",
      p("/admin/users/:userId/sessions/:sessionId/revoke"),
      {
        headers: BearerHeaders,
        params: InstanceUserSessionParams,
        success: InstanceOk,
        error: TargetErrors,
      },
    ),
  )
  .add(
    HttpApiEndpoint.post("workspaceAction", p("/admin/users/:userId/workspace/:action"), {
      headers: BearerHeaders,
      params: InstanceWorkspaceActionParams,
      success: InstanceWorkspace,
      error: TargetErrors,
    }),
  )
  .add(
    HttpApiEndpoint.post("updateWorkspace", p("/admin/users/:userId/workspace"), {
      headers: BearerHeaders,
      params: InstanceUserParams,
      payload: InstanceUpdateWorkspaceRequest,
      success: InstanceWorkspace,
      error: TargetErrors,
    }),
  )
  .add(
    HttpApiEndpoint.get("workspaceLogs", p("/admin/users/:userId/workspace/logs"), {
      headers: BearerHeaders,
      params: InstanceUserParams,
      success: InstanceWorkspaceLogs,
      error: TargetErrors,
    }),
  )
  .add(
    HttpApiEndpoint.get("tools", p("/admin/tools"), {
      headers: BearerHeaders,
      success: InstanceToolCatalog,
      error: CommonErrors,
    }),
  )
  .add(
    HttpApiEndpoint.get("settings", p("/admin/settings"), {
      headers: BearerHeaders,
      success: InstanceSettings,
      error: CommonErrors,
    }),
  )
  .add(
    HttpApiEndpoint.post("updateSettings", p("/admin/settings"), {
      headers: BearerHeaders,
      payload: InstanceSettings,
      success: InstanceSettings,
      error: CommonErrors,
    }),
  )
  .add(
    HttpApiEndpoint.post("upgradeAllWorkspaces", p("/admin/workspaces/upgrade"), {
      headers: BearerHeaders,
      success: InstanceUpgradeAllResult,
      error: CommonErrors,
    }),
  )
  .add(
    HttpApiEndpoint.get("audit", p("/admin/audit"), {
      headers: BearerHeaders,
      query: InstanceAuditQuery,
      success: InstanceAuditPage,
      error: CommonErrors,
    }),
  )
  .middleware(InstanceAdminAuth) {}

class InstanceInternalApi extends HttpApiGroup.make("internal")
  .add(
    HttpApiEndpoint.post("introspect", p("/internal/introspect"), {
      headers: BearerHeaders,
      payload: InstanceIntrospectRequest,
      success: InstanceIntrospectResult,
      error: CommonErrors,
    }),
  )
  .middleware(InstanceWorkspaceAuth) {}

export class InstanceHttpApi extends HttpApi.make("o3-instance")
  .add(InstancePublicApi)
  .add(InstanceAccountApi)
  .add(InstanceAdminApi)
  .add(InstanceInternalApi) {}
